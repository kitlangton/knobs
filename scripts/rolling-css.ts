// Writes src/panel/rolling-css.ts from @kitlangton/rolling-number's stylesheet, so the panel's
// source imports it as a plain module (no text loader in Vite, tsc or Bun). Run after upgrading
// the dependency: `bun scripts/rolling-css.ts`. tests/core.test.ts fails while the two differ.
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
export const rollingSource = () =>
  readFileSync(resolve(root, "node_modules/@kitlangton/rolling-number/dist/styles.css"), "utf8")
export const rollingModule = (css: string) =>
  `// Generated by scripts/rolling-css.ts from @kitlangton/rolling-number/dist/styles.css.\nexport default ${JSON.stringify(css)}\n`

if (import.meta.main) {
  writeFileSync(resolve(root, "src/panel/rolling-css.ts"), rollingModule(rollingSource()))
  console.log("Wrote src/panel/rolling-css.ts")
}
